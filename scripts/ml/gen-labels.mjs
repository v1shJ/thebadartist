import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const source = join(ROOT, 'assets/ml/doodlenet/class_names.txt');
const target = join(ROOT, 'src/ml/modelLabels.ts');

const labels = readFileSync(source, 'utf8')
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter(Boolean);

if (labels.length !== 345) throw new Error(`expected 345 labels, got ${labels.length}`);

const body = labels.map((label) => `  '${label}',`).join('\n');
const out = `// Generated by scripts/ml/gen-labels.mjs from class_names.txt — do not edit.\nexport const MODEL_LABELS = [\n${body}\n] as const;\n`;

writeFileSync(target, out);
console.log('wrote', target, labels.length, 'labels');
